"""Controlled Audit Event Types and taxonomy for Phase 16."""

import enum


class AuditAction(str, enum.Enum):
    """Controlled set of system audit actions."""

    # AUTHENTICATION
    LOGIN_SUCCESS = "LOGIN_SUCCESS"
    LOGIN_FAILURE = "LOGIN_FAILURE"
    LOGOUT = "LOGOUT"

    # TENDER LIFECYCLE
    TENDER_CREATED = "TENDER_CREATED"
    TENDER_UPDATED = "TENDER_UPDATED"
    TENDER_VERSION_CREATED = "TENDER_VERSION_CREATED"
    TENDER_VERSION_PUBLISHED = "TENDER_VERSION_PUBLISHED"
    TENDER_VERSION_CLOSED = "TENDER_VERSION_CLOSED"

    # DOCUMENT & INTEGRITY
    DOCUMENT_UPLOADED = "DOCUMENT_UPLOADED"
    DOCUMENT_HASHED = "DOCUMENT_HASHED"
    DOCUMENT_PROCESSING_STARTED = "DOCUMENT_PROCESSING_STARTED"
    DOCUMENT_PROCESSING_COMPLETED = "DOCUMENT_PROCESSING_COMPLETED"
    DOCUMENT_PROCESSING_FAILED = "DOCUMENT_PROCESSING_FAILED"
    DOCUMENT_ACCESSED = "DOCUMENT_ACCESSED"
    DOCUMENT_INTEGRITY_CHECKED = "DOCUMENT_INTEGRITY_CHECKED"
    DOCUMENT_INTEGRITY_MISMATCH = "DOCUMENT_INTEGRITY_MISMATCH"

    # CRITERIA
    CRITERION_EXTRACTED = "CRITERION_EXTRACTED"
    CRITERION_CORRECTED = "CRITERION_CORRECTED"
    CRITERION_APPROVED = "CRITERION_APPROVED"
    CRITERION_REJECTED = "CRITERION_REJECTED"

    # EVIDENCE
    EVIDENCE_EXTRACTED = "EVIDENCE_EXTRACTED"
    EVIDENCE_NORMALIZED = "EVIDENCE_NORMALIZED"
    EVIDENCE_VALIDATED = "EVIDENCE_VALIDATED"
    EVIDENCE_STATUS_CHANGED = "EVIDENCE_STATUS_CHANGED"

    # RULES & EVALUATIONS
    RULE_CREATED = "RULE_CREATED"
    RULE_VERSION_CREATED = "RULE_VERSION_CREATED"
    CRITERION_EVALUATED = "CRITERION_EVALUATED"
    BIDDER_EVALUATED = "BIDDER_EVALUATED"

    # HUMAN REVIEW & OVERRIDE
    REVIEW_CREATED = "REVIEW_CREATED"
    REVIEW_ASSIGNED = "REVIEW_ASSIGNED"
    REVIEW_NOTE_ADDED = "REVIEW_NOTE_ADDED"
    OFFICER_CONFIRMED = "OFFICER_CONFIRMED"
    OFFICER_OVERRIDDEN = "OFFICER_OVERRIDDEN"
    REVIEW_RESOLVED = "REVIEW_RESOLVED"

    # REPORTS
    REPORT_GENERATED = "REPORT_GENERATED"
    REPORT_DOWNLOADED = "REPORT_DOWNLOADED"
