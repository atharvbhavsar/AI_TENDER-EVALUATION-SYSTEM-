"""CriterionEvaluation entity representing deterministic OPA evaluation outputs."""

import datetime
import enum
import uuid
from typing import TYPE_CHECKING, Any, Dict, List, Optional
from sqlalchemy import (
    DateTime,
    Enum,
    ForeignKey,
    Index,
    JSON,
    String,
    Uuid,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.db.base import Base

if TYPE_CHECKING:
    from app.db.models.bid_submission import BidSubmission
    from app.db.models.bidder import Bidder
    from app.db.models.criterion_rule import CriterionRule
    from app.db.models.tender_criterion import TenderCriterion
    from app.db.models.tender_version import TenderVersion
    from app.db.models.user import User


class EvaluationResult(str, enum.Enum):
    """Deterministic evaluation outcome."""

    ELIGIBLE = "ELIGIBLE"
    NOT_ELIGIBLE = "NOT_ELIGIBLE"
    MANUAL_REVIEW = "MANUAL_REVIEW"


class CriterionEvaluation(Base):
    """
    Immutable evaluation record generated by deterministic OPA/Rego rule evaluation.
    Preserves exact input snapshots, rule versions, evidence citations, and structured explanations.
    """

    __tablename__ = "criterion_evaluations"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    criterion_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("tender_criteria.id", ondelete="RESTRICT"),
        index=True,
        nullable=False,
    )
    bidder_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("bidders.id", ondelete="RESTRICT"),
        index=True,
        nullable=False,
    )
    bid_submission_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("bid_submissions.id", ondelete="RESTRICT"),
        index=True,
        nullable=False,
    )
    tender_version_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("tender_versions.id", ondelete="RESTRICT"),
        index=True,
        nullable=False,
    )
    rule_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("criterion_rules.id", ondelete="RESTRICT"),
        index=True,
        nullable=False,
    )

    rule_version: Mapped[str] = mapped_column(
        String(50), nullable=False
    )
    policy_version: Mapped[str] = mapped_column(
        String(50), nullable=False
    )
    result: Mapped[EvaluationResult] = mapped_column(
        Enum(EvaluationResult, name="evaluation_result_enum", native_enum=False),
        index=True,
        nullable=False,
    )

    input_snapshot: Mapped[Dict[str, Any]] = mapped_column(
        JSON, nullable=False
    )
    evidence_ids: Mapped[List[str]] = mapped_column(
        JSON, nullable=False, default=list
    )
    explanation: Mapped[Dict[str, Any]] = mapped_column(
        JSON, nullable=False, default=dict
    )
    evaluation_run_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        Uuid(as_uuid=True), index=True, nullable=True
    )

    evaluated_by: Mapped[Optional[uuid.UUID]] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    evaluated_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        index=True,
        nullable=False,
    )

    # Relationships
    criterion: Mapped["TenderCriterion"] = relationship("TenderCriterion")
    bidder: Mapped["Bidder"] = relationship("Bidder")
    bid_submission: Mapped["BidSubmission"] = relationship("BidSubmission")
    tender_version: Mapped["TenderVersion"] = relationship("TenderVersion")
    rule: Mapped["CriterionRule"] = relationship("CriterionRule", back_populates="evaluations")
    evaluator: Mapped[Optional["User"]] = relationship("User", foreign_keys=[evaluated_by])

    __table_args__ = (
        Index("ix_eval_submission_criterion", "bid_submission_id", "criterion_id"),
        Index("ix_eval_scope", "tender_version_id", "bidder_id", "bid_submission_id"),
    )

    def __repr__(self) -> str:
        return f"<CriterionEvaluation(id='{self.id}', sub='{self.bid_submission_id}', crit='{self.criterion_id}', result='{self.result}')>"
